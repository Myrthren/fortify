import type { ComposedEmail, Opportunity } from "@/lib/outbound/types";

/**
 * Post-generation quality gate.
 *
 * A prompt is a request, not a guarantee. Every generated email is checked here
 * before it is allowed anywhere near the send queue, and a failure sends the
 * composer round again with the specific violations named. This is the
 * difference between "usually not templated" and "never sends the phrase 'I
 * hope this email finds you well'".
 */


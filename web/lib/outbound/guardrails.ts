  "just following up",
  "just wanted to reach out",
  "just reaching out",
  "quick question",
  "circling back",
  "bumping this",
  "touching base",
  "we help businesses",
  "we help companies",
  "we specialise in helping",
  "we specialize in helping",
  "i wanted to reach out",
  "in today's fast-paced",
  "in today's digital",
  "game-changer",
  "game changer",
  "leverage our",
  "cutting-edge",
  "state-of-the-art",
  "revolutionise your",
  "revolutionize your",
  "take your business to the next level",
  "unlock the power",
  "supercharge your",
  "at the end of the day",
  "let me know if you have any questions",
  "looking forward to hearing from you",
  "i came across your website and",
  "i stumbled upon your",
  "as a fellow",
  "did you see my last email",
